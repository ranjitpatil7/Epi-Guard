import { useState } from 'react';
import { useQuery } from '@tanstack/react-query';
import { getRiskHistory, getSnapshotLineage } from '@/lib/api/riskApi';
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';
import { Badge } from '@/components/ui/badge';
import { Spinner } from '@/components/ui/spinner';
import { Activity, GitCommit } from 'lucide-react';
import { format } from 'date-fns';

export function RiskSnapshotTimeline({ regionId = 1 }: { regionId?: number }) {
  const [selectedSnapshotId, setSelectedSnapshotId] = useState<string | null>(null);

  const { data: history, isLoading: isLoadingHistory } = useQuery({
    queryKey: ['riskHistory', regionId],
    queryFn: () => getRiskHistory(regionId)
  });

  const { data: lineage, isLoading: isLoadingLineage } = useQuery({
    queryKey: ['riskLineage', selectedSnapshotId],
    queryFn: () => getSnapshotLineage(selectedSnapshotId!),
    enabled: !!selectedSnapshotId
  });

  if (isLoadingHistory) {
    return <div className="flex h-32 items-center justify-center"><Spinner /></div>;
  }

  if (!history || history.length === 0) {
    return (
      <div className="flex flex-col items-center justify-center h-32 text-muted-foreground">
        <p>No risk snapshots available.</p>
        <p className="text-xs mt-2">Trigger a demo scenario or wait for real events.</p>
      </div>
    );
  }

  return (
    <div className="grid grid-cols-1 md:grid-cols-3 gap-6">
      {/* Timeline List */}
      <div className="md:col-span-1 border-r border-border/50 pr-4 max-h-[500px] overflow-y-auto">
        <div className="space-y-4 relative">
          {history.map((snap, i) => (
            <div 
              key={snap.snapshot_id} 
              className={`relative pl-6 py-2 cursor-pointer transition-colors hover:bg-muted/50 rounded-md ${selectedSnapshotId === snap.snapshot_id ? 'bg-muted border-l-2 border-primary' : ''}`}
              onClick={() => setSelectedSnapshotId(snap.snapshot_id)}
            >
              <div className="absolute left-0 top-4 w-2 h-2 rounded-full bg-primary" />
              {i < history.length - 1 && (
                <div className="absolute left-1 top-6 bottom-[-20px] w-px bg-border" />
              )}
              
              <div className="flex justify-between items-center mb-1">
                <span className="text-xs text-muted-foreground font-mono">
                  {format(new Date(snap.timestamp), "MMM d, HH:mm:ss")}
                </span>
                <Badge variant={snap.current_risk > 70 ? 'destructive' : snap.current_risk > 40 ? 'warning' : 'success'}>
                  {snap.current_risk.toFixed(1)}
                </Badge>
              </div>
              <div className="text-sm font-medium flex items-center">
                <Activity className="w-3 h-3 mr-1 text-muted-foreground" />
                Delta: {snap.risk_delta > 0 ? '+' : ''}{snap.risk_delta.toFixed(1)}
              </div>
            </div>
          ))}
        </div>
      </div>

      {/* Lineage Details */}
      <div className="md:col-span-2">
        {!selectedSnapshotId ? (
          <div className="flex h-full items-center justify-center text-muted-foreground">
            Select a snapshot from the timeline to view its event lineage.
          </div>
        ) : isLoadingLineage ? (
          <div className="flex h-full items-center justify-center"><Spinner /></div>
        ) : !lineage ? (
          <div className="flex h-full items-center justify-center text-destructive">Failed to load lineage.</div>
        ) : (
          <div className="space-y-4">
            <div className="flex justify-between items-start">
              <div>
                <h3 className="text-lg font-bold flex items-center">
                  <GitCommit className="w-5 h-5 mr-2 text-primary" />
                  Lineage: {lineage.snapshot_id.substring(0, 12)}...
                </h3>
                <p className="text-sm text-muted-foreground">Generated by {lineage.model_version}</p>
              </div>
              <div className="text-right">
                <div className="text-3xl font-bold">{lineage.current_risk.toFixed(1)}</div>
                <div className="text-xs text-muted-foreground">Risk Score</div>
              </div>
            </div>

            {lineage.triggering_event ? (
              <Card className="bg-muted/30 border-primary/20">
                <CardHeader className="pb-2 pt-4">
                  <CardTitle className="text-sm">Triggering Event</CardTitle>
                  <p className="text-sm text-muted-foreground">This snapshot was generated in response to real-time telemetry.</p>
                </CardHeader>
                <CardContent>
                  <div className="flex justify-between items-center bg-background/50 p-3 rounded-md border border-border">
                    <div>
                      <Badge variant="outline" className="mb-1">{lineage.triggering_event.event_type}</Badge>
                      <div className="text-xs text-muted-foreground">Source: {lineage.triggering_event.source}</div>
                    </div>
                    <div className="text-right">
                      <div className="text-xs font-mono">{format(new Date(lineage.triggering_event.timestamp), "HH:mm:ss")}</div>
                    </div>
                  </div>
                </CardContent>
              </Card>
            ) : (
              <div className="text-sm text-muted-foreground italic">Scheduled recalculation (no specific trigger event).</div>
            )}

            <Card>
              <CardHeader className="pb-2 pt-4">
                <CardTitle className="text-sm">Why did the risk change?</CardTitle>
                <p className="text-sm text-muted-foreground">{lineage.explanation.uncertainty_explanation}</p>
              </CardHeader>
              <CardContent>
                <ul className="space-y-3 mt-2">
                  {lineage.explanation.contributing_factors.slice(0, 5).map((factor, idx) => (
                    <li key={idx} className="text-sm border-b border-border/50 pb-2 last:border-0 last:pb-0 flex justify-between">
                      <div>
                        <span className={`mr-2 ${factor.direction === 'positive' ? 'text-destructive' : 'text-emerald-500'}`}>•</span>
                        <span className="font-medium">{factor.feature}</span>
                        <p className="text-xs text-muted-foreground ml-4">{factor.explanation}</p>
                      </div>
                      <div className="font-mono text-xs opacity-70">
                         {factor.impact > 0 ? '+' : ''}{factor.impact.toFixed(1)}
                      </div>
                    </li>
                  ))}
                </ul>
              </CardContent>
            </Card>

          </div>
        )}
      </div>
    </div>
  );
}
